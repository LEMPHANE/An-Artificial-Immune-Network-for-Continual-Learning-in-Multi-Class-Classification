# Metrics: confusion matrix + per-class table
# -------------------------------------------------------------------
class MetricsView(QWidget):
    def __init__(self, parent=None):
        super().__init__(parent)
        lay = QHBoxLayout(self)
        lay.setContentsMargins(0, 0, 0, 0)
        lay.setSpacing(10)

        self.confusion = ConfusionCanvas()
        lay.addWidget(self.confusion, 5)

        self.table = QTableWidget(0, 3)
        self.table.setHorizontalHeaderLabels(["Class", "Accuracy", "n"])
        self.table.horizontalHeaderItem(2).setToolTip("Test samples of this class")
        self.table.verticalHeader().setVisible(False)
        self.table.setEditTriggers(QAbstractItemView.EditTrigger.NoEditTriggers)
        self.table.setSelectionMode(QAbstractItemView.SelectionMode.NoSelection)
        self.table.setFocusPolicy(Qt.FocusPolicy.NoFocus)
        self.table.setShowGrid(False)
        header = self.table.horizontalHeader()
        header.setSectionResizeMode(0, QHeaderView.ResizeMode.Stretch)
        header.setSectionResizeMode(1, QHeaderView.ResizeMode.ResizeToContents)
        header.setSectionResizeMode(2, QHeaderView.ResizeMode.ResizeToContents)
        self.table.setMinimumWidth(250)
        lay.addWidget(self.table, 4)

    def update_metrics(self, m):
        self.confusion.update_confusion(m["confusion"], m["labels"])
        rows = [(c, m["per_class"][c]) for c in m["labels"] if c in m["per_class"]]
        self.table.setRowCount(len(rows))
        for r, (cls, (acc, n)) in enumerate(rows):
            cells = (class_name(cls), f"{acc:.1%}", str(n))
            for c, text in enumerate(cells):
                item = QTableWidgetItem(text)
                if c:
                    item.setTextAlignment(Qt.AlignmentFlag.AlignRight | Qt.AlignmentFlag.AlignVCenter)
                self.table.setItem(r, c, item)

    def clear(self):
        self.confusion.update_confusion([], [])
        self.table.setRowCount(0)
