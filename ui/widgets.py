class TrainingView(QWidget):
    STATS = (("pop", "Population"), ("clones", "Clones added"),
             ("pruned", "Pruned"), ("nearest", "Mean distance"))

    def __init__(self, parent=None):
        super().__init__(parent)
        root = QVBoxLayout(self)
        root.setContentsMargins(0, 0, 0, 0)
        root.setSpacing(8)

        self.headline = QLabel()
        self.headline.setObjectName("viewHeadline")
        self.headline.setWordWrap(True)
        root.addWidget(self.headline)

        row = QHBoxLayout()
        row.setSpacing(8)
        self._stats = {}
        for key, title in self.STATS:
            lab = QLabel()
            lab.setObjectName("statLabel")
            lab.setTextFormat(Qt.TextFormat.RichText)
            row.addWidget(lab, 1)
            self._stats[key] = (lab, title)
        root.addLayout(row)

        self.curve = TrainCurveCanvas()
        root.addWidget(self.curve, 1)

        self.log = QPlainTextEdit()
        self.log.setReadOnly(True)
        self.log.setMaximumBlockCount(300)
        self.log.setMaximumHeight(84)
        root.addWidget(self.log)

        self.reset()

    def _stat(self, key, value):
        lab, title = self._stats[key]
        lab.setText(f"<span style='color:#A5A9B2;font-size:8pt'>{title}</span><br>"
                    f"<span style='color:#F5F6F8;font-size:13pt'>{value}</span>")

    def reset(self):
        self.headline.setText("Idle. Load classes and press Train.")
        for key, _ in self.STATS:
            self._stat(key, "-")
        self.curve.reset()
        self.log.clear()

    # ---- worker events -------------------------------------------------
    def on_train_started(self, classes, total_steps):
        names = ", ".join(short_name(c) for c in classes)
        self.headline.setText(f"Training {len(classes)} class(es): {names}")
        self.log.appendPlainText(f"Training {len(classes)} class(es), {total_steps} steps in total")

    def on_class_started(self, info):
        self.headline.setText(
            f"Class {info['k']} of {info['n_classes']}: {class_name(info['cls'])} "
            f"({info['n_antigens']} antigens)")
        self.log.appendPlainText(f"-- {class_name(info['cls'])}: population {info['population']}")

    def on_epoch_done(self, info):
        self._stat("pop", f"{info['pop_start']} → {info['pop_end']}")
        self._stat("clones", str(info["clones_added"]))
        self._stat("pruned", str(info["pruned"]))
        self._stat("nearest", f"{info['nearest']:.3f}")
        self.curve.add_point(info["cls"], info["epoch"], info["nearest"])
        self.log.appendPlainText(
            f"   epoch {info['epoch']}/{info['epochs']}: distance {info['nearest']:.3f}, "
            f"population {info['pop_start']} → {info['pop_end']} "
            f"(+{info['clones_added']} clones, -{info['pruned']} pruned)")

    def on_class_done(self, cls, memory_size):
        self.log.appendPlainText(f"   {class_name(cls)} done: memory pool now {memory_size} cells")

    def on_evaluated(self, m):
        self.log.appendPlainText(
            f"   eval at {m['stage']} classes: accuracy {m['accuracy']:.1%}, "
            f"balanced {m['balanced_accuracy']:.1%}")

    def note(self, text):
        self.headline.setText(text)
        self.log.appendPlainText(text)


