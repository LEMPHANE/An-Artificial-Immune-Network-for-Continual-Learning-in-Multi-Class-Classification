# Memory: PCA distance map + grid of memory cells
# -------------------------------------------------------------------
class MemoryView(QWidget):
    def __init__(self, parent=None):
        super().__init__(parent)
        lay = QVBoxLayout(self)
        lay.setContentsMargins(0, 0, 0, 0)

        self.tabs = QTabWidget()
        self.pca = PCACanvas()
        self.grid = MemoryGridCanvas()
        scroll = QScrollArea()
        scroll.setWidgetResizable(True)
        scroll.setWidget(self.grid)
        scroll.setFrameShape(QScrollArea.Shape.NoFrame)
        self.tabs.addTab(self.pca, "Distance map (PCA)")
        self.tabs.addTab(scroll, "Memory cells")
        lay.addWidget(self.tabs)

        self._grid_args = None
        self.tabs.currentChanged.connect(lambda _i: self._flush_grid())

    def set_memory(self, vecs, cls, antigens, antigen_cls, memory_size):
        self.pca.update_data(vecs, cls, antigens, antigen_cls)
        self._grid_args = SimpleNamespace(mem_vecs=vecs, mem_cls=cls, memory_size=memory_size)
        self._flush_grid()

    def clear(self):
        self.pca.update_data(None, None)
        self.grid.clear()
        self._grid_args = None

    # The grid is ~200 images: only draw it when it can actually be seen.
    def _flush_grid(self):
        if self._grid_args is not None and self.isVisible() and self.tabs.currentIndex() == 1:
            args, self._grid_args = self._grid_args, None
            self.grid.update_model(args)

    def showEvent(self, event):
        super().showEvent(event)
        self._flush_grid()


