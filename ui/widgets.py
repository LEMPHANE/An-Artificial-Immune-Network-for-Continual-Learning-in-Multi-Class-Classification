class LoaderDialog(QDialog):
    """Pick one or more classes, press OK (or Enter) to load them; Cancel (or Esc) does nothing.

    Classes already loaded or trained are greyed out. Selected classes come back in ascending
    label order, which is also the order they are queued for training.
    """

    def __init__(self, store, parent=None):
        super().__init__(parent)
        self.store = store

        self.ui = Ui_DataLoad()
        self.ui.setupUi(self)

        # pyuic numbered the buttons out of order, so map them by geometry:
        # sorted by (row, column) -> index 0-9 = MNIST digits, 10-19 = Fashion-MNIST (label offset +10)
        buttons = sorted(self.findChildren(QToolButton), key=lambda b: (b.geometry().y(), b.geometry().x()))
        self.class_buttons = {label: btn for label, btn in enumerate(buttons)}

        for label, btn in self.class_buttons.items():
            btn.setCheckable(True)
            btn.setText("")
            btn.setToolButtonStyle(Qt.ToolButtonStyle.ToolButtonIconOnly)
            btn.setIconSize(QSize(26, 26))
            btn.setToolTip(CLASS_NAMES[label])
            btn.setEnabled(False)  # enabled once the data is ready

        self.ui.buttonBox.button(QDialogButtonBox.StandardButton.Ok).setDefault(True)

        if store.is_ready():
            self._populate()
        else:
            self.setWindowTitle("Select a class (loading datasets...)")
            store.ready.connect(self._populate)
            store.failed.connect(self._on_failed)

    def _populate(self):
        self.setWindowTitle("Select a class")
        for label, btn in self.class_buttons.items():
            btn.setIcon(self.store.icon(label))
            if self.store.is_trained(label):
                btn.setEnabled(False)  # in the model already: visible but greyed out
                btn.setToolTip(f"{CLASS_NAMES[label]} (already trained)")
            elif self.store.is_loaded(label):
                btn.setEnabled(False)
                btn.setToolTip(f"{CLASS_NAMES[label]} (already loaded)")
            else:
                btn.setEnabled(True)

    def _on_failed(self, msg):
        self.setWindowTitle("Dataset loading failed - see status bar")

    def selected_labels(self):
        return [lab for lab, btn in self.class_buttons.items() if btn.isEnabled() and btn.isChecked()]

    def keyPressEvent(self, event):
        # Enter/Return -> OK even when a tool button has focus; Esc -> Cancel (QDialog default)
        if event.key() in (Qt.Key.Key_Return, Qt.Key.Key_Enter):
            self.accept()
            return
        super().keyPressEvent(event)


